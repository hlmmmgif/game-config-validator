from llm_client import ask

def make_report(check_text):
    system = (
        "你是游戏数值与配置表审核员。你会收到程序自动生成的一段检查结果，"
        "任务是把这段结果翻译成策划能立刻看懂的说明。\n"
        "表结构：（7 列，判断某列能否为空以此为准，不许自己推测）：\n"
        "物品ID：被分解的物品，必填，为空则整行无效\n"
        "分解产物1_ID：第一个产物，必填\n"
        "产物1数量：必填，正整数\n"
        "分解产物2_ID：第二个产物，可为空，为空表示只有一种产物\n"
        "产物2数量：可为空，无第二产物时填 0\n"
        "分解手续费：必填，不能为负\n"
        "分解耗时(秒)：必填\n"
        "要求："
        "1. 按玩家能不能靠这个问题不当获利分组，分两组：【必须改】：玩家能借此多拿资源、或游戏会崩溃卡死【建议改】：只是填写方式不对，游戏里看不出异常\n"
        "2. 典型例子：手续费为负、产物数量为负、产物ID引用不存在的物品 → 一律算【必须改】，理由要说明玩家会怎么利用它获利\n"
        "3. 不要复述原文的报错句子，用大白话解释\n"
        "4. 不要重新计算任何数值，不要补充原文没有提到的问题\n"
        "5. 用简洁通顺的中文，直接输出说明正文，不要加标题和多余的解释，不要出现错别字和病句"
    )
    user = f"以下是检查结果：\n{check_text}\n\n请按上述要求生成说明。"
    return ask(user, system=system)
